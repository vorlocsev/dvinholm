using System.Globalization;

namespace Dvinholm.App;

/// <summary>
/// Reads the numeric 10% download milestones emitted by UpdateDownloadProgress.
/// Other updater stages do not have a measurable overall percentage and keep
/// the WinUI progress bar indeterminate.
/// </summary>
internal static class UpdateDownloadPercentage
{
    internal static bool TryRead(string? text, out int percent)
    {
        percent = 0;
        if (text is null || !text.StartsWith("Downloading ", StringComparison.Ordinal))
            return false;

        // The version is validated by the updater, and every download message
        // is generated by our byte counter. Parse only the known status shape.
        var marker = text.LastIndexOf(": ", StringComparison.Ordinal);
        if (marker < "Downloading ".Length)
            return false;

        var suffix = text.AsSpan(marker + 2);
        var percentEnd = suffix.IndexOf("% (".AsSpan(), StringComparison.Ordinal);
        if (percentEnd < 1 ||
            !int.TryParse(suffix[..percentEnd], NumberStyles.None, CultureInfo.InvariantCulture, out var value) ||
            value is < 10 or > 100 || value % 10 != 0)
            return false;

        var counts = suffix[(percentEnd + 3)..];
        if (!counts.EndsWith(" bytes)".AsSpan(), StringComparison.Ordinal))
            return false;

        var copiedAndExpected = counts[..^" bytes)".Length];
        var slash = copiedAndExpected.IndexOf('/');
        if (slash < 1 || slash == copiedAndExpected.Length - 1)
            return false;

        percent = value;
        return true;
    }
}
